"""Generate crates/machine-mega65/src/keytable.rs: the ASCII value of each
key of the C65 keyboard matrix (column x 8 + row) alone and with SHIFT,
CTRL, MEGA and ALT, as the MEGA65 user guide's keyboard appendix lists them.
The guide makes those tables (keymap.c) from the data tables of the MEGA65
core's matrix_to_ascii.vhdl; this script reads the same five tables (the
"N => x"HH"" lines only).

    python tools/gen_mega65_keymap.py matrix_to_ascii.vhdl crates/machine-mega65/src/keytable.rs

The input file is not part of this repository.
"""

import re
import sys

src, out = sys.argv[1], sys.argv[2]
names = ['normal', 'shift', 'control', 'cbm', 'alt']
tables = {}
current = None
for line in open(src, encoding='utf-8', errors='replace'):
    m = re.search(r'signal matrix_(\w+) : key_matrix_t', line)
    if m and m.group(1) in names:
        current = m.group(1)
        tables[current] = [0] * 72
        continue
    if current:
        m = re.match(r'\s*(\d+)\s*=>\s*x"([0-9a-fA-F]{2})"', line)
        if m:
            k = int(m.group(1))
            if k < 72:
                tables[current][k] = int(m.group(2), 16)
        if ');' in line:
            current = None

lines = [
    '//! The ASCII value of each key of the C65 keyboard matrix (index column',
    '//! x 8 + row) alone and with SHIFT, CTRL, MEGA and ALT: the tables of the',
    '//! MEGA65 user guide\'s keyboard appendix ("Interpreting ASCII Typing',
    '//! Events"), generated by `tools/gen_mega65_keymap.py` from the data the',
    '//! guide\'s tables are made from. 0: no ASCII interpretation.',
    '',
]
for n in names:
    t = tables[n]
    lines.append('pub const %s: [u8; 72] = [' % n.upper())
    for i in range(0, 72, 12):
        lines.append('    ' + ', '.join('0x%02x' % v for v in t[i:i + 12]) + ',')
    lines.append('];')
    lines.append('')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('ok', {n: sum(1 for v in tables[n] if v) for n in names})
