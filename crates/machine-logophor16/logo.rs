//! Foundry's start picture (step 9): the owner's Logophor 16 emblem
//! (`asm/foundry/logo.png`, 640 × 360, scaled from the owner's 1672 × 941
//! original), made at build time into a mode-0 picture: 320 × 180 by
//! averaging 2 × 2 pixels, 256 colours by median cut (entry 0 kept black
//! for the borders), the palette in RGB 5:6:5. Also the keyboard tables
//! (USB HID usage → ISO 8859-1, US layout, unshifted and shifted).
//!
//! `logo.inc` holds `logo_pal` (256 words) and `logo_pix` (57 600 bytes,
//! row by row); `keys.inc` holds `keymap` and `keymap_shift` (usages
//! $00–$38).

use std::fmt::Write;

pub const W: usize = 320;
pub const H: usize = 180;

fn pixels(png_bytes: &[u8]) -> Vec<[u8; 3]> {
    let dec = png::Decoder::new(std::io::Cursor::new(png_bytes));
    let mut r = dec.read_info().expect("logo.png");
    let mut buf = vec![0; r.output_buffer_size()];
    let info = r.next_frame(&mut buf).expect("logo.png");
    assert_eq!((info.width, info.height), (640, 360), "logo.png: 640 x 360");
    let ch = match info.color_type {
        png::ColorType::Rgb => 3,
        png::ColorType::Rgba => 4,
        t => panic!("logo.png: colour type {t:?}"),
    };
    let at = |x: usize, y: usize, c: usize| u32::from(buf[(y * 640 + x) * ch + c]);
    let mut out = Vec::with_capacity(W * H);
    for y in 0..H {
        for x in 0..W {
            let mut p = [0u8; 3];
            for (c, v) in p.iter_mut().enumerate() {
                let s = at(2 * x, 2 * y, c)
                    + at(2 * x + 1, 2 * y, c)
                    + at(2 * x, 2 * y + 1, c)
                    + at(2 * x + 1, 2 * y + 1, c);
                *v = ((s + 2) / 4) as u8;
            }
            out.push(p);
        }
    }
    out
}

/// Median cut: split the box with the widest channel range at its
/// median until there are `n` boxes; each box's mean is a colour.
pub fn median_cut(px: &[[u8; 3]], n: usize) -> Vec<[u8; 3]> {
    let mut boxes: Vec<Vec<[u8; 3]>> = vec![px.to_vec()];
    let range = |b: &[[u8; 3]], c: usize| {
        let (lo, hi) = b
            .iter()
            .fold((255u8, 0u8), |(l, h), p| (l.min(p[c]), h.max(p[c])));
        hi.saturating_sub(lo)
    };
    while boxes.len() < n {
        // The box to split: widest range (ties: the larger box, then the first).
        let (i, c) = boxes
            .iter()
            .enumerate()
            .filter(|(_, b)| b.len() > 1)
            .flat_map(|(i, b)| (0..3).map(move |c| (i, c, range(b, c), b.len())))
            .max_by(|a, b| {
                (a.2, a.3)
                    .cmp(&(b.2, b.3))
                    .then(b.0.cmp(&a.0))
                    .then(b.1.cmp(&a.1))
            })
            .map(|(i, c, _, _)| (i, c))
            .unwrap_or((0, 0));
        if boxes[i].len() < 2 {
            break;
        }
        let mut b = boxes.swap_remove(i);
        b.sort_by_key(|p| (p[c], p[(c + 1) % 3], p[(c + 2) % 3]));
        let rest = b.split_off(b.len() / 2);
        boxes.push(b);
        boxes.push(rest);
    }
    boxes
        .iter()
        .map(|b| {
            let mut s = [0u64; 3];
            for p in b {
                for c in 0..3 {
                    s[c] += u64::from(p[c]);
                }
            }
            let n = b.len().max(1) as u64;
            s.map(|v| ((v + n / 2) / n) as u8)
        })
        .collect()
}

pub fn rgb565(p: [u8; 3]) -> u16 {
    // Rounded to the nearest level of each channel.
    let q = |v: u8, bits: u32| ((u32::from(v) * ((1 << bits) - 1) + 127) / 255) as u16;
    q(p[0], 5) << 11 | q(p[1], 6) << 5 | q(p[2], 5)
}

pub fn logo_inc(png_bytes: &[u8]) -> String {
    let px = pixels(png_bytes);
    let mut pal = vec![[0u8; 3]];
    pal.extend(median_cut(&px, 255));
    pal.resize(256, [0, 0, 0]);
    let index: Vec<u8> = px
        .iter()
        .map(|p| {
            let d = |q: &[u8; 3]| {
                (0..3)
                    .map(|c| (i32::from(p[c]) - i32::from(q[c])).pow(2))
                    .sum::<i32>()
            };
            (0..256).min_by_key(|&i| (d(&pal[i]), i)).unwrap() as u8
        })
        .collect();
    let mut out = String::from("; generated by build.rs (logo.rs) from asm/foundry/logo.png\n        .align  2\nlogo_pal:\n");
    for row in pal.chunks(8) {
        let w: Vec<String> = row.iter().map(|p| format!("${:04x}", rgb565(*p))).collect();
        writeln!(out, "        .word   {}", w.join(",")).unwrap();
    }
    out.push_str("logo_pix:\n");
    for row in index.chunks(32) {
        let b: Vec<String> = row.iter().map(|v| format!("${v:02x}")).collect();
        writeln!(out, "        .byte   {}", b.join(",")).unwrap();
    }
    out
}

/// ISO 8859-1 for HID usages $00–$38 (US layout), unshifted and shifted;
/// 0 where a key gives no character.
pub fn keys_inc() -> String {
    let mut plain = [0u8; 0x39];
    let mut shift = [0u8; 0x39];
    for i in 0..26 {
        plain[4 + i] = b'a' + i as u8;
        shift[4 + i] = b'A' + i as u8;
    }
    let digits = b"1234567890";
    let shifted = b"!@#$%^&*()";
    plain[0x1e..0x28].copy_from_slice(digits);
    shift[0x1e..0x28].copy_from_slice(shifted);
    for (u, p, s) in [
        (0x28, 13, 13),
        (0x29, 27, 27),
        (0x2a, 8, 8),
        (0x2b, 9, 9),
        (0x2c, b' ', b' '),
        (0x2d, b'-', b'_'),
        (0x2e, b'=', b'+'),
        (0x2f, b'[', b'{'),
        (0x30, b']', b'}'),
        (0x31, b'\\', b'|'),
        (0x32, b'#', b'~'),
        (0x33, b';', b':'),
        (0x34, b'\'', b'"'),
        (0x35, b'`', b'~'),
        (0x36, b',', b'<'),
        (0x37, b'.', b'>'),
        (0x38, b'/', b'?'),
    ] {
        plain[u] = p;
        shift[u] = s;
    }
    let mut out = String::from("; generated by build.rs (logo.rs): HID usage -> character\n");
    for (name, t) in [("keymap", plain), ("keymap_shift", shift)] {
        writeln!(out, "{name}:").unwrap();
        for row in t.chunks(16) {
            let b: Vec<String> = row.iter().map(|v| format!("${v:02x}")).collect();
            writeln!(out, "        .byte   {}", b.join(",")).unwrap();
        }
    }
    out
}
