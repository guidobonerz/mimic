//! Builds the Foundry ROM from `asm/foundry/foundry.s` with asm-ada (the
//! machine needs no user files) and the 8 × 16 system font it includes:
//! the first 256 characters (ISO 8859-1) of Martin Sedlák's Sweet16mono
//! (`asm/foundry/sweet16mono.f8`, 16 bytes a character, leftmost pixel in
//! bit 7; Boost Software License 1.0, `asm/foundry/LICENSE-Sweet16`;
//! <https://github.com/kmar/Sweet16Font>). The font leaves $00–$20 and
//! $80–$A0 blank.

use std::path::{Path, PathBuf};

#[path = "logo.rs"]
mod logo;
#[path = "music.rs"]
mod music;
mod tile;
#[path = "zeppelin.rs"]
mod zeppelin;

struct Sources {
    font: String,
    zeppelin: (String, String),
    music: (String, String),
    logo: String,
    keys: String,
}

impl asm_ada::Files for Sources {
    fn read(&self, path: &Path) -> Result<String, String> {
        match path.file_name().and_then(|n| n.to_str()) {
            Some("font.inc") => return Ok(self.font.clone()),
            Some("zeppelin.inc") => return Ok(self.zeppelin.0.clone()),
            Some("zeppelin_data.inc") => return Ok(self.zeppelin.1.clone()),
            Some("music.inc") => return Ok(self.music.0.clone()),
            Some("music_data.inc") => return Ok(self.music.1.clone()),
            Some("logo.inc") => return Ok(self.logo.clone()),
            Some("keys.inc") => return Ok(self.keys.clone()),
            _ => {}
        }
        asm_ada::HostFiles.read(path)
    }
}

fn font(f8: &[u8]) -> String {
    let mut out = String::from(
        "; generated by build.rs from sweet16mono.f8: 256 characters x 16 lines
",
    );
    for (c, rows) in f8.chunks(16).take(256).enumerate() {
        let bytes: Vec<String> = rows.iter().map(|b| format!("${b:02x}")).collect();
        out.push_str(&format!(
            "        .byte {}   ; ${c:02x}
",
            bytes.join(",")
        ));
    }
    out
}

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("asm/foundry");
    println!("cargo:rerun-if-changed={}", dir.display());
    let main = dir.join("foundry.s");
    let src = std::fs::read_to_string(&main).expect("asm/foundry/foundry.s");
    let f8 = std::fs::read(dir.join("sweet16mono.f8")).expect("asm/foundry/sweet16mono.f8");
    assert!(f8.len() >= 256 * 16, "sweet16mono.f8: 256 characters");
    println!("cargo:rerun-if-changed=zeppelin.rs");
    println!("cargo:rerun-if-changed=music.rs");
    println!("cargo:rerun-if-changed=logo.rs");
    let png = std::fs::read(dir.join("logo.png")).expect("asm/foundry/logo.png");
    let files = Sources {
        font: font(&f8),
        zeppelin: zeppelin::includes(),
        music: music::includes(),
        logo: logo::logo_inc(&png),
        keys: logo::keys_inc(),
    };
    let obj = asm_ada::assemble(&main.display().to_string(), &src, &files)
        .unwrap_or_else(|e| panic!("Foundry ROM:\n{}", e.join("\n")));
    let img = asm_ada::link(&[obj], asm_ada::Options::default())
        .unwrap_or_else(|e| panic!("Foundry ROM:\n{}", e.join("\n")));
    let rom = img.flat(0xfffb_0000, 0x4_0000, 0xff);
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("foundry.rom"), rom).expect("write foundry.rom");
    std::fs::write(out.join("foundry.lst"), img.listing).expect("write foundry.lst");
    system_card(&out);
}

/// The system card (option `card=system`): Boiler, Panorama and its
/// applications compiled from `system/` as BOOT/BOILER.BIN on a 64 MiB
/// FAT32 card, kept sparse: the sector count, then each sector that is
/// not all zero as its number and its 512 bytes (little-endian numbers).
fn system_card(out: &Path) {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("system");
    // (a directory: cargo looks at everything below it)
    println!("cargo:rerun-if-changed={}", root.display());
    let png = std::fs::read(Path::new(env!("CARGO_MANIFEST_DIR")).join("system/panorama/tile.png"))
        .expect("system/panorama/tile.png");
    // the dock's application tiles (system/panorama/icons/), by name
    let icons: Vec<(String, Vec<u8>)> = [
        ("Info", "info"),
        ("Archive", "archive"),
        ("Engine Room", "engine"),
        ("Radio", "radio"),
        ("Pathfinder", "pathfinder"),
        ("Steamworks", "steamworks"),
    ]
    .iter()
    .map(|(name, file)| {
        let p = root.join(format!("panorama/icons/{file}.png"));
        (name.to_string(), std::fs::read(&p).expect("icon"))
    })
    .collect();
    let wallpaper = std::fs::read(root.join("panorama/wallpaper.png")).expect("wallpaper.png");
    let buttons = std::fs::read(root.join("panorama/buttons.png")).expect("buttons.png");
    let skin = tile::tile_raw(&png, &wallpaper, &buttons, &icons);
    std::fs::write(out.join("tile.raw"), &skin).expect("write tile.raw");
    let prog = brass::build(&brass::DirSources { root })
        .unwrap_or_else(|e| panic!("system/:\n{}", e.join("\n")));
    let readme = b"The Logophor 16's system card: Boiler, Panorama and its applications.\n\
        BOOT/BOILER.BIN is started by Foundry's boot loader.\n";
    let img = asm_ada::sdimage::fat32(
        64,
        &[
            ("BOOT/BOILER.BIN".into(), prog.binary),
            ("README.TXT".into(), readme.to_vec()),
            ("PANORAMA/TILE.RAW".into(), skin),
        ],
    )
    .expect("system card");
    let mut sparse = Vec::new();
    sparse.extend_from_slice(&((img.len() / 512) as u32).to_le_bytes());
    for (i, sector) in img.chunks(512).enumerate() {
        if sector.iter().any(|&b| b != 0) {
            sparse.extend_from_slice(&(i as u32).to_le_bytes());
            sparse.extend_from_slice(sector);
        }
    }
    std::fs::write(out.join("system-card.bin"), sparse).expect("write system-card.bin");
}
